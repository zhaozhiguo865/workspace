В последние годы популярность приобрели фитнес, йога, пилатес. Люди заботятся о здоровье, следят за фигурой. Танцы, боулинг, бильярд — всё это способ весело провести время с друзьями."

# 生成语音函数
generate_speech() {
    local text="$1"
    local output="$2"
    
    echo "生成: $output"
    
    curl -s -X POST \
        "https://tts.api.cloud.yandex.net/speech/v1/tts:synthesize" \
        -H "Authorization: Api-Key $API_KEY" \
        -d "text=$(echo "$text" | jq -sRr @uri)" \
        -d "lang=ru-RU" \
        -d "voice=alena" \
        -d "speed=1.0" \
        -o "$output"
    
    if [ -f "$output" ] && [ -s "$output" ]; then
        echo "✓ 完成: $output ($(stat -f%z "$output" 2>/dev/null || stat -c%s "$output" 2>/dev/null) bytes)"
    else
        echo "✗ 失败: $output"
    fi
}

echo "=== Yandex SpeechKit TTS ==="
echo "输出目录: $OUTPUT_DIR"
echo ""

# 生成各课语音
generate_speech "$LESSON1" "$OUTPUT_DIR/book4_lesson1.mp3"
generate_speech "$LESSON2" "$OUTPUT_DIR/book4_lesson2.mp3"
generate_speech "$LESSON3" "$OUTPUT_DIR/book4_lesson3.mp3"

echo ""
echo "=== 完成 ==="
echo "使用前请设置 YANDEX_API_KEY 环境变量"
