#!/bin/bash
# Yandex SpeechKit TTS 脚本 - 第四册课文

# 需要设置 YANDEX_API_KEY 环境变量
# 获取 API Key: https://yandex.cloud/ru/docs/speechkit/quickstart

API_KEY="${YANDEX_API_KEY:-}"
if [ -z "$API_KEY" ]; then
    echo "错误: 请设置 YANDEX_API_KEY 环境变量"
    echo "获取 API Key: https://yandex.cloud/ru/docs/speechkit/quickstart"
    exit 1
fi

OUTPUT_DIR="${1:-.}"
mkdir -p "$OUTPUT_DIR"

# Урок 1
